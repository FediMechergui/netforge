/** A template document as a P2 world: `profile: 'P2'` and the schema that can express it (1.2). */
function asP2Document(t: Topology): Topology {
  return { ...t, schema: TOPOLOGY_SCHEMA_ID_1_2, profile: 'P2' };
}

/** The world as the worker's `loadScenario` loads it: seed, lab stamp when the entry has tasks, scheduled faults. */
function loadLike(sc: ScenarioInfo, topo: Topology): Simulation {
  const sim = createSimulation({ seed: sc.seed ?? SCENARIO_SEED });
  sim.loadTopology((sc.tasks?.length ?? 0) > 0 ? { ...topo, lab: { name: sc.name, version: sc.version ?? 1 } } : topo);
  for (const f of sc.faults ?? []) sim.injectFault(f.at, f.fault);
  return sim;
}

function templateWorld(sc: ScenarioInfo): P2World {
  const script = TEMPLATE_SCRIPTS[sc.name];
  if (script === undefined) throw new Error(`the P2 digest script has no entry for template ${sc.name}`);
  return {
    name: sc.name,
    shard: 'templates',
    seed: sc.seed ?? SCENARIO_SEED,
    build: () => loadLike(sc, asP2Document(sc.build())),
    setup: {},
    probes: [script.ping],
    show: script.show,
  };
}

function labWorld(sc: ScenarioInfo, index: number): P2World {
  const script = LAB_SCRIPTS[sc.name];
  if (script === undefined) throw new Error(`the P2 digest script has no entry for lab ${sc.name}`);
  return {
    name: sc.name,
    shard: index < LABS_A_COUNT ? 'labs-a' : 'labs-b',
    seed: sc.seed ?? SCENARIO_SEED,
    build: () => loadLike(sc, sc.build()),
    setup: sc.solution ?? {},
    probes: [script.ping],
    show: script.show,
  };
}

