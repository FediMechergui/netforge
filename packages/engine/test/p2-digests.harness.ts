/** Startup text: each section's lines followed by `!`, then `end`. */
function startup(sections: readonly (readonly string[])[]): string {
  const out: string[] = [];
  for (const s of sections) out.push(...s, '!');
  out.push('end', '');
  return out.join('\n');
}

/**
 * PC1 and PC2 (DHCP) and R1 (the DHCP server, 192.168.1.1) on SW1, whose Vlan1 is 192.168.1.2/24 and up. The PCs'
 * DISCOVER and REQUEST broadcasts reach the SVI; R1 traceroutes to it and PC1's browser fetches `http://<SVI>/`.
 */
function guardDocument(profile: 'P1' | 'P2'): Topology {
  const at = (x: number, y: number): { logical: [number, number] } => ({ logical: [x, y] });
  const t: Topology = {
    schema: profile === 'P2' ? TOPOLOGY_SCHEMA_ID_1_2 : TOPOLOGY_SCHEMA_ID_1_1,
    seed: GUARD_SEED,
    devices: [
      {
        id: 'r1', type: 'router.nf2911', name: 'R1', position: at(500, 120), power: true,
        config: startup([
          ['hostname R1'],
          ['interface GigabitEthernet0/0', ' ip address 192.168.1.1 255.255.255.0', ' no shutdown'],
          ['ip dhcp excluded-address 192.168.1.1 192.168.1.10'],
          ['ip dhcp pool GUARD', ' network 192.168.1.0 255.255.255.0', ' default-router 192.168.1.1'],
        ]),
      },
      {
        id: 'sw1', type: 'switch.nfc2960', name: 'SW1', position: at(300, 220), power: true,
        config: startup([['hostname SW1'], ['interface Vlan1', ` ip address ${GUARD_SVI} 255.255.255.0`, ' no shutdown'], ['ip default-gateway 192.168.1.1']]),
      },
      { id: 'pc1', type: 'pc.nfpc', name: 'PC1', position: at(100, 340), power: true, config: startup([['hostname PC1']]) },
      { id: 'pc2', type: 'pc.nfpc', name: 'PC2', position: at(300, 400), power: true, config: startup([['hostname PC2']]) },
    ],
    links: [
      { id: 'l_pc1_sw1', a: { device: 'pc1', port: 'GigabitEthernet0' }, b: { device: 'sw1', port: 'FastEthernet0/1' }, media: 'auto', length_m: 3 },
      { id: 'l_pc2_sw1', a: { device: 'pc2', port: 'GigabitEthernet0' }, b: { device: 'sw1', port: 'FastEthernet0/2' }, media: 'auto', length_m: 3 },
      { id: 'l_r1_sw1', a: { device: 'r1', port: 'GigabitEthernet0/0' }, b: { device: 'sw1', port: 'GigabitEthernet0/1' }, media: 'auto', length_m: 3 },
    ],
  };
  return profile === 'P2' ? { ...t, profile: 'P2' } : t;
}

function guardWorld(profile: 'P1' | 'P2'): P2World {
  return {
    name: GUARD_WORLDS[profile],
    shard: 'guards',
    seed: GUARD_SEED,
    build: () => {
      const sim = createSimulation({ seed: GUARD_SEED });
      sim.loadTopology(guardDocument(profile));
      return sim;
    },
    setup: { PC1: ['ip address dhcp'], PC2: ['ip address dhcp'] },
    probes: [
      { kind: 'cli', device: 'R1', line: `traceroute ${GUARD_SVI}` },
      { kind: 'browse', device: 'PC1', url: `http://${GUARD_SVI}/` },
    ],
    show: ['R1', 'show ip dhcp binding'],
  };
}

/** Every world of the golden, in golden order (read at call time, rule 12). */
export function p2Worlds(): readonly P2World[] {
  return [
    ...TEMPLATES.map(templateWorld),
    ...CCNA2_LABS.map((sc, i) => labWorld(sc, i)),
    sandboxWorld(),
    guardWorld('P1'),
    guardWorld('P2'),
  ];
}

/** The worlds of one shard, in golden order. */
export function shardWorlds(shard: P2DigestShard): readonly P2World[] {
  return p2Worlds().filter((w) => w.shard === shard);
}

