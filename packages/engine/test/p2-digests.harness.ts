const SHA256_H0 = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19] as const;

const rotr = (x: number, n: number): number => (x >>> n) | (x << (32 - n));

/** Lower-case hex SHA-256 of the UTF-8 bytes of `text`. */
export function sha256Hex(text: string): string {
  const data = new TextEncoder().encode(text);
  const blocks = Math.ceil((data.length + 9) / 64);
  const buf = new Uint8Array(blocks * 64);
  buf.set(data);
  buf[data.length] = 0x80;
  const view = new DataView(buf.buffer);
  view.setUint32(buf.length - 8, Math.floor(data.length / 0x20000000));
  view.setUint32(buf.length - 4, (data.length * 8) >>> 0);
  const h: number[] = [...SHA256_H0];
  const w: number[] = new Array<number>(64).fill(0);
  for (let base = 0; base < buf.length; base += 64) {
    for (let i = 0; i < 16; i++) w[i] = view.getInt32(base + i * 4);
    for (let i = 16; i < 64; i++) {
      const x = w[i - 15]!;
      const y = w[i - 2]!;
      const s0 = rotr(x, 7) ^ rotr(x, 18) ^ (x >>> 3);
      const s1 = rotr(y, 17) ^ rotr(y, 19) ^ (y >>> 10);
      w[i] = (w[i - 16]! + s0 + w[i - 7]! + s1) | 0;
    }
    let [a, b, c, d, e, f, g, hh] = h as [number, number, number, number, number, number, number, number];
    for (let i = 0; i < 64; i++) {
      const t1 = (hh + (rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25)) + ((e & f) ^ (~e & g)) + SHA256_K[i]! + w[i]!) | 0;
      const t2 = ((rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22)) + ((a & b) ^ (a & c) ^ (b & c))) | 0;
      hh = g;
      g = f;
      f = e;
      e = (d + t1) | 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) | 0;
    }
    const out = [a, b, c, d, e, f, g, hh];
    for (let i = 0; i < 8; i++) h[i] = (h[i]! + out[i]!) | 0;
  }
  return h.map((x) => (x >>> 0).toString(16).padStart(8, '0')).join('');
}

/** `<t>|<kind>|<16 hex>` — byte-identical to the harness `p0EventLine`, with the SHA-256 above. */
export function eventLine(ev: TraceEvent, owners: ReadonlyMap<string, string>): string {
  const normalized = normalizeP0Event(ev, owners);
  return `${String(normalized.t)}|${String(normalized.kind)}|${sha256Hex(canonicalJson(normalized)).slice(0, 16)}`;
}

// ── background attribution (D3) ─────────────────────────────────────────────

/** A JSON object's members (an empty record when `value` is not an object). */
function recordOf(value: unknown): Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value) ? (value as Record<string, unknown>) : {};
}

/** `value` as a list (empty when it is not one). */
function listOf(value: unknown): unknown[] {
  return Array.isArray(value) ? (value as unknown[]) : [];
}

/** A PDU id as a map key (ids are numbers; a string id is accepted too). */
function pduKey(value: unknown): string | undefined {
  return typeof value === 'number' || typeof value === 'string' ? String(value) : undefined;
}

/** The PDUs an event references (empty for events about no PDU). */
export function referencedPdus(ev: TraceEvent): string[] {
  const e = ev as unknown as Record<string, unknown>;
  const keys: (string | undefined)[] = [];
  switch (ev.kind) {
    case 'frameTx':
    case 'frameRx':
    case 'frameAbort':
    case 'drop':
    case 'pduCreated':
    case 'pduConsumed':
      keys.push(pduKey(recordOf(e['pdu'])['id']));
      break;
    case 'mutation':
    case 'backoff':
    case 'carrierDefer':
      keys.push(pduKey(e['pdu']));
      break;
    case 'collision':
      for (const id of listOf(e['pdus'])) keys.push(pduKey(id));
      break;
    case 'debug':
      keys.push(pduKey(recordOf(ev.event.data)['pdu']));
      break;
    default:
      break;
  }
  return keys.filter((k): k is string => k !== undefined);
}

/** Per event: true when it is attributable to a background PDU (every PDU it references is background). */
export function backgroundFlags(events: readonly TraceEvent[]): boolean[] {
  const background = new Set<string>();
  const parentOf = new Map<string, string>();
  for (const ev of events) {
    const e = ev as unknown as Record<string, unknown>;
    const summary = recordOf(e['pdu']);
    const id = pduKey(summary['id']);
    if (id === undefined) continue;
    const parent = pduKey(summary['parent']);
    if (parent !== undefined) parentOf.set(id, parent);
    if ((ev.kind === 'frameTx' || ev.kind === 'drop') && e['background'] === true) background.add(id);
  }
  // a clone of a background PDU is background (clone chains are short; iterate to the fixpoint)
  for (let changed = true; changed; ) {
    changed = false;
    for (const [child, parent] of parentOf) {
      if (!background.has(child) && background.has(parent)) {
        background.add(child);
        changed = true;
      }
    }
  }
  return events.map((ev) => {
    const refs = referencedPdus(ev);
    return refs.length > 0 && refs.every((r) => background.has(r));
  });
}

// ── the snapshot normalisation (§4.6 item 2) ────────────────────────────────

/** The contract data the normalisation reads (the real contracts, read at call time; a test passes its own). */
export interface NormalisationContracts {
  readonly capabilityProcesses: Readonly<Record<string, readonly { readonly process: string; readonly since: string }[]>>;
  readonly processTables: Readonly<Record<string, readonly string[] | undefined>>;
  readonly tableDescriptors: Readonly<Record<string, { readonly since: string } | undefined>>;
}

function realContracts(): NormalisationContracts {
  return {
    capabilityProcesses: CAPABILITY_PROCESSES as unknown as NormalisationContracts['capabilityProcesses'],
    processTables: PROCESS_TABLES as unknown as NormalisationContracts['processTables'],
    tableDescriptors: TABLE_DESCRIPTORS as unknown as NormalisationContracts['tableDescriptors'],
  };
}

/**
 * THE rule of §4.6 item 2: a JSON copy of `snapshot` where each device loses the StateViews and owned tables of the
 * processes it runs outside `vocab.processes` or derives only through capability rows of a stage the golden did not
 * have, every extra table outside `vocab.tables` or whose descriptor is of such a stage (a list left empty is
 * dropped), the members of `capabilities`, `gui` and `allowedRoles` outside the vocabulary, and every port's P3
 * display member `txBacklog` (the FIFO view, D16, ruling R6). The P0 frame count `txQueue` is kept. Nothing else
 * is touched.
 */
export function normaliseSnapshot(snapshot: SimSnapshot, vocab: P2Vocabulary, contracts: NormalisationContracts = realContracts()): Record<string, unknown> {
  const stages = new Set(vocab.stages);
  const processes = new Set(vocab.processes);
  const tables = new Set(vocab.tables);
  const capabilities = new Set(vocab.capabilities);
  const guiPanels = new Set(vocab.guiPanels);
  const portRoles = new Set(vocab.portRoles);
  const copy = JSON.parse(JSON.stringify(snapshot)) as Record<string, unknown>;
  for (const d of listOf(copy['devices']).map(recordOf)) {
    const caps = listOf(d['capabilities']).map(String);
    const rowsOf = (process: string): { readonly since: string }[] => caps.flatMap((c) => (contracts.capabilityProcesses[c] ?? []).filter((r) => r.process === process));
    const laterOnly = (process: string): boolean => {
      const rows = rowsOf(process);
      return rows.length > 0 && rows.every((r) => !stages.has(r.since));
    };
    const running = listOf(d['processes']).map((v) => String(recordOf(v)['process']));
    const dropped = new Set(running.filter((p) => !processes.has(p) || laterOnly(p)));
    const kept = running.filter((p) => !dropped.has(p));
    const keptTables = new Set(kept.flatMap((p) => contracts.processTables[p] ?? []));
    const droppedTables = new Set([...dropped].flatMap((p) => contracts.processTables[p] ?? []).filter((t) => !keptTables.has(t)));
    if (Array.isArray(d['processes'])) d['processes'] = listOf(d['processes']).filter((v) => !dropped.has(String(recordOf(v)['process'])));
    const t = recordOf(d['tables']);
    if (Array.isArray(t['extra'])) {
      const keep = (name: string): boolean => {
        const since = contracts.tableDescriptors[name]?.since;
        return tables.has(name) && (since === undefined || stages.has(since)) && !droppedTables.has(name);
      };
      const extra = listOf(t['extra']).filter((x) => keep(String(recordOf(x)['name'])));
      if (extra.length === 0) delete t['extra'];
      else t['extra'] = extra;
    }
    if (Array.isArray(d['capabilities'])) d['capabilities'] = listOf(d['capabilities']).filter((c) => capabilities.has(String(c)));
    if (Array.isArray(d['gui'])) d['gui'] = listOf(d['gui']).filter((g) => guiPanels.has(String(g)));
    for (const p of listOf(d['ports']).map(recordOf)) {
      if (Array.isArray(p['allowedRoles'])) p['allowedRoles'] = listOf(p['allowedRoles']).filter((r) => portRoles.has(String(r)));
      delete p['txBacklog'];
    }
  }
  return copy;
}

/** 16-hex hashes of each device (`devices/<id>`) and of every other top-level member of a normalised snapshot. */
function snapshotParts(normalised: Record<string, unknown>): Record<string, string> {
  const parts: Record<string, string> = {};
  for (const key of Object.keys(normalised).sort()) {
    if (key === 'devices') {
      for (const d of listOf(normalised[key]).map(recordOf)) parts[`devices/${String(d['id'])}`] = sha256Hex(canonicalJson(d)).slice(0, 16);
    } else {
      parts[key] = sha256Hex(canonicalJson(normalised[key])).slice(0, 16);
    }
  }
  return parts;
}

/** The part of a normalised snapshot a `snapshotParts` key names. */
function snapshotPart(normalised: Record<string, unknown>, key: string): unknown {
  if (!key.startsWith('devices/')) return normalised[key];
  const id = key.slice('devices/'.length);
  return listOf(normalised['devices']).find((d) => String(recordOf(d)['id']) === id);
}

// ── one run of a world ──────────────────────────────────────────────────────

/** One scripted run of a world: its golden entry plus what the reports and the guard facts need. */
export interface WorldRun {
  readonly world: P2World;
  readonly entry: WorldEntry;
  readonly events: readonly TraceEvent[];
  /** The line of every event (the golden stores only the non-background ones). */
  readonly lines: readonly string[];
  readonly background: readonly boolean[];
  readonly owners: ReadonlyMap<string, string>;
  readonly normalised: Record<string, unknown>;
  /** Setup lines the CLI refused (`<device>: <line>: <message>`). */
  readonly refused: readonly string[];
  /** Trace events the ring evicted (must be 0: every event is digested). */
  readonly dropped: number;
  /** Per probe, the cliOutput text of its session (empty for a browser fetch). */
  readonly reports: readonly string[];
  /** Device name → id in this world. */
  readonly ids: ReadonlyMap<string, DeviceId>;
}

/** Device id of a topology name. */
function idOf(sim: Simulation, name: string): DeviceId {
  for (const d of sim.devices()) if (d.spec.name === name) return d.id;
  throw new Error(`no device called ${name} in this world`);
}

/** Type `line` on a fresh console of `name`, keeping a JSON copy of the result. */
function typeLine(sim: Simulation, name: string, line: string): { typed: TypedResult; session: SessionId } {
  const session = sim.cli.open(idOf(sim, name), 'console');
  const result = sim.cli.exec(session, line);
  return { typed: { device: name, line, result: JSON.parse(JSON.stringify(result)) as unknown }, session };
}

/** The http-client tab a browser ticket owns. */
function browserTab(sim: Simulation, device: DeviceId, token: string): unknown {
  const state = sim.device(device)?.processes.get('http-client')?.stateSnapshot().state;
  const tabs = recordOf(state?.['tabs']);
  return JSON.parse(JSON.stringify(tabs[token] ?? {})) as unknown;
}

/** Start a probe at t = 90 s; `finish` (at 110 s) gives its typed record. */
function startProbe(sim: Simulation, p: Probe): { finish(): TypedResult; session?: SessionId } {
  if (p.kind === 'cli') {
    const { typed, session } = typeLine(sim, p.device, p.line);
    return { finish: () => typed, session };
  }
  const device = idOf(sim, p.device);
  const ticket = JSON.parse(JSON.stringify(sim.hostRequest(device, { app: 'http.get', url: p.url }))) as Record<string, unknown>;
  return { finish: () => ({ device: p.device, line: `browse ${p.url}`, result: { ticket, tab: browserTab(sim, device, String(ticket['requestId'])) } }) };
}

/** Per-kind counts, keys sorted. */
function countKinds(events: readonly TraceEvent[]): Record<string, number> {
  const counts = new Map<string, number>();
  for (const ev of events) counts.set(ev.kind, (counts.get(ev.kind) ?? 0) + 1);
  const out: Record<string, number> = {};
  for (const k of [...counts.keys()].sort()) out[k] = counts.get(k)!;
  return out;
}

/** Window index of an event line (`<t>|…`). */
function windowOf(line: string): number {
  return Math.floor(Number(line.slice(0, line.indexOf('|'))) / WINDOW_NS);
}

/** `<count>:<16 hex>` of each 10-second window up to the one holding `endNs`. */
function windowDigests(lines: readonly string[], endNs: number): string[] {
  const buckets: string[][] = Array.from({ length: Math.floor(endNs / WINDOW_NS) + 1 }, () => []);
  for (const line of lines) {
    const w = windowOf(line);
    while (buckets.length <= w) buckets.push([]);
    buckets[w]!.push(line);
  }
  return buckets.map((b) => `${b.length}:${sha256Hex(b.join('\n')).slice(0, 16)}`);
}

/** Run the fixed script on `w` from a fresh simulation. */
function runWorld(w: P2World): WorldRun {
  const sim = w.build();
  sim.runFor(BOOT_NS);

  const refused: string[] = [];
  for (const [name, lines] of Object.entries(w.setup)) {
    const r = sim.configure(idOf(sim, name), lines);
    for (const l of r.lines) if (!l.ok) refused.push(`${name}: ${l.line}: ${l.error?.message ?? l.output}`);
  }
  sim.runFor(SETTLE_NS);

  const probes = w.probes.map((p) => startProbe(sim, p));
  sim.runFor(PROBE_NS);
  const typed = probes.map((p) => p.finish());
  typed.push(typeLine(sim, w.show[0], w.show[1]).typed);
  sim.runFor(RUN_NS);

  const trace = sim.trace(0);
  const snapshot = sim.snapshot();
  const owners = macOwners(snapshot);
  const events = trace.events;
  const lines = events.map((ev) => eventLine(ev, owners));
  const background = backgroundFlags(events);
  const normalised = normaliseSnapshot(snapshot, p2Vocabulary());
  const reports = probes.map((p) => {
    let text = '';
    if (p.session !== undefined) for (const ev of events) if (ev.kind === 'cliOutput' && ev.session === p.session) text += ev.text;
    return text;
  });
  const ids = new Map<string, DeviceId>();
  for (const d of sim.devices()) ids.set(d.spec.name, d.id);
  const entry: WorldEntry = {
    profile: sim.profile,
    seed: sim.seed,
    endNs: sim.now,
    typed,
    eventCount: lines.length,
    eventsDigest: sha256Hex(lines.join('\n')),
    kinds: countKinds(events),
    windows: windowDigests(lines, sim.now),
    snapshot: sha256Hex(canonicalJson(normalised)),
    snapshotParts: snapshotParts(normalised),
    events: lines.filter((_, i) => !background[i]),
  };
  return { world: w, entry, events, lines, background, owners, normalised, refused, dropped: trace.dropped, reports, ids };
}

const runCache = new Map<string, WorldRun>();

/** The scripted run of `w` (once per test file run: the script is deterministic). */
export function freshRun(w: P2World): WorldRun {
  let run = runCache.get(w.name);
  if (run === undefined) {
    run = runWorld(w);
    runCache.set(w.name, run);
  }
  return run;
}

// ── the guard facts (D22) ───────────────────────────────────────────────────

/**
 * What the two guard worlds must show for the D22 guard to measure something (§10.1 `-guards`): every DISCOVER and
 * REQUEST that reaches the switch SVI dies in ipv4 as `unsupported-protocol`, the switch answers the traceroute and
 * the fetch with ICMP protocol unreachable and delivers nothing to udp or tcp, the traceroute stops on the
 * protocol-unreachable flag `!2` (ICMP code 2), and the fetch ends in an error tab. Returns the facts that do not hold.
 */
export function guardProblems(run: WorldRun): string[] {
  const sw = run.ids.get('SW1');
  const problems: string[] = [];
  const drops = run.events.filter((ev): ev is Extract<TraceEvent, { kind: 'drop' }> => ev.kind === 'drop' && ev.device === sw);
  const dhcpDrops = drops.filter((ev) => ev.pdu.proto === 'dhcp');
  for (const tag of ['dhcp-discover', 'dhcp-request']) {
    const seen = dhcpDrops.filter((ev) => ev.pdu.tag === tag);
    const clients = new Set(seen.map((ev) => ev.pdu.summary.replace(/^.* xid=/, '')));
    if (clients.size < 2) problems.push(`expected a ${tag} from each PC to die at the switch SVI, saw ${seen.length} from ${clients.size} client(s)`);
  }
  const wrong = dhcpDrops.filter((ev) => ev.reason !== 'unsupported-protocol');
  if (wrong.length > 0) problems.push(`DHCP broadcasts dropped at the switch for another reason: ${wrong.map((ev) => ev.reason).join(', ')}`);
  const upper = run.events.filter((ev) => (ev.kind === 'pduConsumed' || ev.kind === 'pduCreated') && ev.device === sw && (ev.process === 'udp' || ev.process === 'tcp'));
  if (upper.length > 0) problems.push(`udp or tcp on the switch handled ${upper.length} PDUs`);
  // ICMP 3/2 from the switch: three for the traceroute's UDP probes, one for the fetch's SYN
  const unreachable = run.events.filter(
    (ev): ev is Extract<TraceEvent, { kind: 'pduCreated' }> => ev.kind === 'pduCreated' && ev.device === sw && ev.process === 'icmpv4' && ev.pdu.summary === 'ICMP destination unreachable (protocol)',
  );
  const answered = (proto: string): number => unreachable.filter((ev) => (ev.pdu.flow ?? '').endsWith(`:${proto}`)).length;
  if (answered('udp') < 3) problems.push(`expected ICMP protocol unreachable for each traceroute probe, saw ${answered('udp')}`);
  if (answered('tcp') < 1) problems.push(`expected ICMP protocol unreachable for the fetch's SYN, saw ${answered('tcp')}`);
  for (const ev of drops.filter((d) => d.pdu.proto === 'udp' || d.pdu.proto === 'tcp')) {
    if (ev.reason !== 'unsupported-protocol') problems.push(`a ${ev.pdu.proto} packet died at the switch as ${ev.reason}, not unsupported-protocol`);
  }
  // the router's report: every probe of hop 1 answered with the protocol-unreachable flag (ICMP code 2), then stop
  const trace = run.reports[0] ?? '';
  if (!trace.includes(`1 ${GUARD_SVI} !2 !2 !2\n`) || !trace.includes(`Stopped at hop 1: ${GUARD_SVI} is unreachable.`)) {
    problems.push(`the traceroute did not stop on the protocol-unreachable flag: ${JSON.stringify(trace)}`);
  }
  const fetch = recordOf(recordOf(run.entry.typed[1]?.result)['tab']);
  if (fetch['phase'] !== 'error' || fetch['error'] !== 'The connection failed (proto-unreachable).') {
    problems.push(`the browser fetch did not fail on protocol unreachable: ${JSON.stringify(fetch)}`);
  }
  return problems;
}

// ── readable reports ────────────────────────────────────────────────────────

/** `text` cut to `max` characters. */
function clip(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max)}… (${text.length - max} more characters)`;
}

/** The normalised JSON of the run's event `i`, clipped. */
function runEventJson(run: WorldRun, i: number, max: number): string {
  const ev = run.events[i];
  return ev === undefined ? '' : clip(canonicalJson(normalizeP0Event(ev, run.owners)), max);
}

/** Indices (into `run.events`) of the run's stored (non-background) events. */
function storedIndices(run: WorldRun): number[] {
  const out: number[] = [];
  run.background.forEach((bg, i) => {
    if (!bg) out.push(i);
  });
  return out;
}

/** Largest middle section the per-event diff aligns exactly (golden events × run events). */
const DIFF_CELLS = 4_000_000;

/**
 * Per-event diff of the golden's stored lines against the run's: `-` golden-only events, `+` run-only events with
 * their normalised JSON. A longest-common-subsequence alignment of the section between the common prefix and suffix;
 * at most `limit` changed events are listed.
 */
function eventDiff(expected: readonly string[], run: WorldRun, limit: number): string[] {
  const actual = run.entry.events;
  const index = storedIndices(run);
  let lo = 0;
  while (lo < expected.length && lo < actual.length && expected[lo] === actual[lo]) lo++;
  let hiE = expected.length;
  let hiA = actual.length;
  while (hiE > lo && hiA > lo && expected[hiE - 1] === actual[hiA - 1]) {
    hiE--;
    hiA--;
  }
  const n = hiE - lo;
  const m = hiA - lo;
  const out: string[] = [];
  const minus = (i: number): void => void out.push(`  - golden #${i}  ${expected[i]}`);
  const plus = (j: number): void => void out.push(`  + run    #${j}  ${actual[j]}  ${runEventJson(run, index[j] ?? -1, 240)}`);
  if (n * m > DIFF_CELLS) {
    for (let k = 0; k < limit && (lo + k < hiE || lo + k < hiA); k++) {
      if (lo + k < hiE) minus(lo + k);
      if (lo + k < hiA) plus(lo + k);
    }
    out.push(`  (the differing sections are too long to align: ${n} golden and ${m} run events)`);
    return out;
  }
  const width = m + 1;
  const lcs = new Uint32Array((n + 1) * width);
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      lcs[i * width + j] = expected[lo + i] === actual[lo + j] ? lcs[(i + 1) * width + j + 1]! + 1 : Math.max(lcs[(i + 1) * width + j]!, lcs[i * width + j + 1]!);
    }
  }
  let i = 0;
  let j = 0;
  let changes = 0;
  while ((i < n || j < m) && changes < limit) {
    if (i < n && j < m && expected[lo + i] === actual[lo + j]) {
      i++;
      j++;
    } else if (i < n && (j === m || lcs[(i + 1) * width + j]! >= lcs[i * width + j + 1]!)) {
      minus(lo + i++);
      changes++;
    } else {
      plus(lo + j++);
      changes++;
    }
  }
  if (i < n || j < m) out.push('  … (more changed events not listed)');
  return out;
}

/** The kinds whose counts moved, as `kind a → b`. */
function movedKinds(before: Readonly<Record<string, number>>, after: Readonly<Record<string, number>>): string[] {
  return [...new Set([...Object.keys(before), ...Object.keys(after)])]
    .sort()
    .filter((k) => before[k] !== after[k])
    .map((k) => `${k} ${before[k] ?? 0} → ${after[k] ?? 0}`);
}

/**
 * Empty when the run's events equal the golden's (every digest, count, window and stored line); otherwise a report
 * naming the world, the windows that differ, the first diverging stored event and the per-kind counts that moved.
 */
function eventReport(name: string, expected: WorldEntry, run: WorldRun): string {
  const got = run.entry;
  const same =
    expected.eventCount === got.eventCount &&
    expected.eventsDigest === got.eventsDigest &&
    canonicalJson(expected.kinds) === canonicalJson(got.kinds) &&
    canonicalJson(expected.windows) === canonicalJson(got.windows) &&
    canonicalJson(expected.events) === canonicalJson(got.events);
  if (same) return '';
  const out = [
    `P2-profile trace of world "${name}" differs from test/goldens/p2-profile-digests.json (§9.4 lists the only allowed changes).`,
    `Events: the golden has ${expected.eventCount}, this run ${got.eventCount}; digest ${expected.eventsDigest.slice(0, 16)} → ${got.eventsDigest.slice(0, 16)}.`,
  ];
  const moved = movedKinds(expected.kinds, got.kinds);
  out.push(`Event counts that changed: ${moved.length === 0 ? 'none (same kinds and counts, different content or order)' : moved.join(', ')}.`);
  const windows: string[] = [];
  for (let k = 0; k < Math.max(expected.windows.length, got.windows.length); k++) {
    if (expected.windows[k] !== got.windows[k]) windows.push(`[${k * (WINDOW_NS / SEC)} s, ${(k + 1) * (WINDOW_NS / SEC)} s) ${expected.windows[k] ?? '(none)'} → ${got.windows[k] ?? '(none)'}`);
  }
  out.push(`Windows that differ (count:digest, golden → run): ${windows.length === 0 ? 'none' : ''}`, ...windows.slice(0, 20).map((w) => `  ${w}`));
  if (windows.length > 20) out.push(`  … and ${windows.length - 20} more windows`);
  const firstWindow = expected.windows.findIndex((w, k) => w !== got.windows[k]);
  const e = expected.events;
  const a = got.events;
  let first = 0;
  while (first < e.length && first < a.length && e[first] === a[first]) first++;
  if (first === e.length && first === a.length) {
    out.push('Every stored (non-background) event is unchanged: the change is in events attributable to a background PDU.');
    if (firstWindow >= 0) {
      const inWindow = run.lines.map((l, i) => ({ l, i })).filter(({ l, i }) => run.background[i] && windowOf(l) === firstWindow);
      out.push(`This run's background events in the first differing window [${firstWindow * (WINDOW_NS / SEC)} s, ${(firstWindow + 1) * (WINDOW_NS / SEC)} s) (first 20):`);
      for (const { l, i } of inWindow.slice(0, 20)) out.push(`  #${i}  ${l}  ${runEventJson(run, i, 240)}`);
    }
  } else {
    const index = storedIndices(run);
    out.push(
      `First diverging stored event: #${first} (the golden stores ${e.length} events, this run ${a.length}).`,
      `  golden: ${e[first] ?? '(no more events)'}`,
      `  run:    ${a[first] ?? '(no more events)'}`,
    );
    if (first < a.length) out.push(`  run event (normalised): ${runEventJson(run, index[first] ?? -1, 1500)}`);
    out.push('Per-event diff of the stored events (golden → run, first 40 changes):', ...eventDiff(e, run, 40));
  }
  return out.join('\n');
}

/** Empty when the normalised snapshot equals the golden's; otherwise the parts that differ, with the run's JSON. */
function snapshotReport(name: string, expected: WorldEntry, run: WorldRun): string {
  if (expected.snapshot === run.entry.snapshot) return '';
  const got = run.entry.snapshotParts;
  const keys = [...new Set([...Object.keys(expected.snapshotParts), ...Object.keys(got)])].sort();
  const out = [`Normalised end snapshot of world "${name}" differs from the golden (hash ${expected.snapshot} → ${run.entry.snapshot}).`];
  for (const key of keys) {
    const was = expected.snapshotParts[key];
    const now = got[key];
    if (was === now) continue;
    if (was === undefined) out.push(`  ${key}: not in the golden; run: ${clip(canonicalJson(snapshotPart(run.normalised, key)), 1500)}`);
    else if (now === undefined) out.push(`  ${key}: in the golden, missing from this run`);
    else out.push(`  ${key}: differs; run: ${clip(canonicalJson(snapshotPart(run.normalised, key)), 1500)}`);
  }
  if (out.length === 1) out.push('  every part hashes the same: the device order changed');
  return out.join('\n');
}

// ── recording (the architect, §9.4) ─────────────────────────────────────────

/** Names the recording switch asks for (read at call time). */
function recordSwitch(): string {
  return (process.env['NF_RECORD_P2_DIGESTS'] ?? '').trim();
}

/** Why a fresh run may not be recorded (empty when it may). */
function recordProblems(run: WorldRun): string[] {
  const problems = [...run.refused];
  for (const t of run.entry.typed) {
    const error = recordOf(t.result)['error'];
    if (error !== undefined) problems.push(`${t.device}> ${t.line}: ${canonicalJson(error)}`);
  }
  run.world.probes.forEach((p, i) => {
    if (p.kind === 'cli' && p.line.startsWith('ping ') && !/received [1-9]|Received = [1-9]|Success rate is [1-9]/.test(run.reports[i] ?? '')) {
      problems.push(`the ping got no reply: ${JSON.stringify(run.reports[i])}`);
    }
  });
  if (run.dropped !== 0) problems.push(`the trace ring evicted ${run.dropped} events`);
  if (run.world.shard === 'guards') problems.push(...guardProblems(run));
  return problems;
}

/** Sleep `ms` milliseconds synchronously (the lock wait). */
function sleepSync(ms: number): void {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

/** Run `fn` holding the golden's lock file, so shards recording in parallel merge instead of overwriting each other. */
function withGoldenLock<T>(fn: () => T): T {
  const deadline = Date.now() + 120_000;
  let fd: number | undefined;
  while (fd === undefined) {
    try {
      fd = openSync(LOCK_PATH, 'wx');
    } catch (e) {
      if (Date.now() > deadline) throw new Error(`could not take ${LOCK_PATH} within 120 s (a recording crashed? delete the file): ${String(e)}`);
      sleepSync(50);
    }
  }
  try {
    return fn();
  } finally {
    closeSync(fd);
    unlinkSync(LOCK_PATH);
  }
}

/** Re-record the worlds of `shard` the switch names, merging them into the golden file under its lock. */
function record(shard: P2DigestShard): void {
  const all = p2Worlds();
  const wanted = recordSwitch();
  const names = wanted === 'all' ? all.filter((w) => w.shard === shard).map((w) => w.name) : wanted.split(',').map((s) => s.trim()).filter((s) => s !== '');
  for (const name of names) if (!all.some((w) => w.name === name)) throw new Error(`NF_RECORD_P2_DIGESTS names ${name}, which is not a P2-profile golden world`);
  const mine = all.filter((w) => w.shard === shard && names.includes(w.name));
  if (mine.length === 0) return;
  const runs = mine.map((w) => {
    const run = freshRun(w);
    const problems = recordProblems(run);
    if (problems.length > 0) throw new Error(`refusing to record ${w.name}:\n  ${problems.join('\n  ')}`);
    return run;
  });
  withGoldenLock(() => {
    const previous = existsSync(GOLDEN_URL) ? (JSON.parse(readFileSync(GOLDEN_URL, 'utf8')) as GoldenFile) : undefined;
    if (previous !== undefined && canonicalJson(previous.script) !== canonicalJson(SCRIPT_TIMES) && wanted !== 'all') {
      throw new Error('the script timings changed: that re-records every world (NF_RECORD_P2_DIGESTS=all, every shard)');
    }
    const fresh = new Map(runs.map((r) => [r.world.name, r.entry]));
    const worldsOut: Record<string, WorldEntry> = {};
    for (const w of all) {
      const old = previous?.worlds[w.name];
      const now = fresh.get(w.name);
      if (now === undefined) {
        if (old !== undefined) worldsOut[w.name] = old;
        continue;
      }
      if (old !== undefined) {
        const run = runs.find((r) => r.world.name === w.name)!;
        const report = [eventReport(w.name, old, run), snapshotReport(w.name, old, run)].filter((r) => r !== '').join('\n');
        console.log(report === '' && canonicalJson(old) === canonicalJson(now) ? `${w.name}: unchanged` : `${w.name}: re-recorded\n${report}`);
      }
      worldsOut[w.name] = now;
    }
    const file: GoldenFile = { about: ABOUT, script: SCRIPT_TIMES, p2Vocabulary: previous?.p2Vocabulary ?? currentVocabulary(), worlds: worldsOut };
    writeFileSync(GOLDEN_URL, `${JSON.stringify(file, null, 2)}\n`);
    // read back from disk at the next use: shards recording in parallel merge their own entries after this one
    goldenCache = undefined;
  });
}

