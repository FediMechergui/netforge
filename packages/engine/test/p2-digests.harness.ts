/** The synthetic §4.6 case: a later-stage transport on a managed switch goes, a router's P1 transport stays. */
function normalisationCase(): { input: SimSnapshot; vocab: P2Vocabulary; contracts: NormalisationContracts; expected: unknown } {
  const vocab: P2Vocabulary = {
    stages: ['P0', 'P0.5', 'P1', 'P2'],
    processes: ['eth-switch', 'ipv4', 'udp', 'tcp', 'stp'],
    tables: ['cam', 'arp', 'rib', 'sockets', 'stp'],
    capabilities: ['switching', 'managed-switch', 'routing'],
    guiPanels: ['config'],
    portRoles: ['switchport', 'l3'],
  };
  const contracts: NormalisationContracts = {
    capabilityProcesses: {
      switching: [{ process: 'eth-switch', since: 'P0' }, { process: 'ipv4', since: 'P1' }],
      'managed-switch': [{ process: 'stp', since: 'P2' }, { process: 'udp', since: 'P3' }, { process: 'tcp', since: 'P3' }, { process: 'cdp', since: 'P3' }],
      routing: [{ process: 'ipv4', since: 'P0' }, { process: 'udp', since: 'P1' }, { process: 'tcp', since: 'P1' }, { process: 'cdp', since: 'P3' }],
      programmable: [],
    },
    processTables: { udp: ['sockets'], tcp: ['sockets'], stp: ['stp'], cdp: ['cdp'] },
    tableDescriptors: { cam: { since: 'P0' }, sockets: { since: 'P1' }, stp: { since: 'P2' }, cdp: { since: 'P3' }, 'dhcp-snooping': { since: 'P3' } },
  };
  const views = (names: readonly string[]): { process: string; state: Record<string, unknown> }[] => names.map((process) => ({ process, state: { n: 1 } }));
  const extra = (names: readonly string[]): { name: string; rows: unknown[] }[] => names.map((name) => ({ name, rows: [] }));
  const port = { id: 'Gi0/1', allowedRoles: ['switchport', 'l3', 'wan-p3'], txQueue: 0, mac: '02:00:00:00:00:01' };
  const input = {
    now: 1,
    devices: [
      {
        id: 'sw1', capabilities: ['switching', 'managed-switch', 'programmable'], gui: ['config', 'desktop.traffic'],
        processes: views(['eth-switch', 'ipv4', 'stp', 'udp', 'tcp', 'cdp']), tables: { cam: [], extra: extra(['sockets', 'stp', 'cdp', 'dhcp-snooping']) },
        ports: [port],
      },
      {
        id: 'r1', capabilities: ['routing'], gui: ['config'], processes: views(['ipv4', 'udp', 'tcp', 'cdp']), tables: { cam: [], extra: extra(['sockets', 'cdp']) },
        ports: [{ ...port, txQueue: 3, txBacklog: { depth: 2, frames: [] } }],
      },
    ],
  } as unknown as SimSnapshot;
  // The P3 display member `txBacklog` goes; the P0 frame count `txQueue` stays with its value.
  const kept = (txQueue: number): Record<string, unknown> => ({ id: 'Gi0/1', allowedRoles: ['switchport', 'l3'], txQueue, mac: '02:00:00:00:00:01' });
  const expected = {
    now: 1,
    devices: [
      { id: 'sw1', capabilities: ['switching', 'managed-switch'], gui: ['config'], processes: views(['eth-switch', 'ipv4', 'stp']), tables: { cam: [], extra: extra(['stp']) }, ports: [kept(0)] },
      { id: 'r1', capabilities: ['routing'], gui: ['config'], processes: views(['ipv4', 'udp', 'tcp']), tables: { cam: [], extra: extra(['sockets']) }, ports: [kept(3)] },
    ],
  };
  return { input, vocab, contracts, expected };
}

/**
 * The suite of one shard: coverage, the SHA-256 and background proofs, the P2 guard of the normalisation, and one
 * case per world comparing every digest, count, window, stored line, typed result and the normalised snapshot.
 */
export function describeP2DigestShard(shard: P2DigestShard, title: string): void {
  describe(title, () => {
    // Regeneration is a step before the comparison, not a test: an ordinary run neither records nor skips anything.
    beforeAll(() => {
      if (recordSwitch() !== '') record(shard);
    }, RECORD_TIMEOUT_MS);

    it('covers its worlds of the 32-world P2 golden with the fixed script', () => {
      const all = p2Worlds();
      expect(all.map((w) => w.name)).toEqual([
        ...TEMPLATES.map((s) => s.name),
        ...CCNA2_LAB_NAMES,
        SANDBOX_WORLD,
        GUARD_WORLDS.P1,
        GUARD_WORLDS.P2,
      ]);
      expect(all).toHaveLength(32);
      expect(CCNA2_LABS.map((s) => s.name)).toEqual(CCNA2_LAB_NAMES);
      expect(Object.keys(TEMPLATE_SCRIPTS)).toEqual(TEMPLATES.map((s) => s.name));
      const counts = { templates: 9, 'labs-a': 10, 'labs-b': 11, guards: 2 } as const;
      expect(shardWorlds(shard)).toHaveLength(counts[shard]);
      const keys = Object.keys(golden().worlds);
      // golden order is world order; in a recording run the other shards may still be merging their own entries
      expect(keys).toEqual(all.map((w) => w.name).filter((n) => keys.includes(n)));
      if (recordSwitch() === '') expect(keys).toEqual(all.map((w) => w.name));
      else for (const w of shardWorlds(shard)) expect(keys, w.name).toContain(w.name);
      expect(golden().script).toEqual(SCRIPT_TIMES);
      expect(golden().about).toBe(ABOUT);
    });

    it('hashes with a plain TypeScript SHA-256 whose event lines are exactly the harness p0EventLine', () => {
      expect(sha256Hex('')).toBe('e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855');
      expect(sha256Hex('abc')).toBe('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
      expect(sha256Hex('abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq')).toBe('248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1');
      for (const w of shardWorlds(shard)) {
        const run = freshRun(w);
        expect(run.lines, w.name).toEqual(run.events.map((ev) => p0EventLine(ev, run.owners)));
      }
    }, SHARD_CASE_TIMEOUT_MS);

    it('stores every event not attributable to a background PDU, and only those', () => {
      for (const w of shardWorlds(shard)) {
        const run = freshRun(w);
        // every event that references no PDU is stored; a frameTx or drop flagged background never is
        run.events.forEach((ev, i) => {
          if (referencedPdus(ev).length === 0) expect(run.background[i], `${w.name} #${i} ${ev.kind}`).toBe(false);
          const flagged = (ev.kind === 'frameTx' || ev.kind === 'drop') && (ev as unknown as { background?: boolean }).background === true;
          if (flagged) expect(run.background[i], `${w.name} #${i} ${ev.kind}`).toBe(true);
        });
        expect(run.entry.events.length, w.name).toBe(run.background.filter((b) => !b).length);
      }
    }, SHARD_CASE_TIMEOUT_MS);

    it('normalises the snapshot by removing only what a later stage adds (§4.6)', () => {
      const p2 = golden().p2Vocabulary;
      const now = currentVocabulary();
      // Nothing the P2 engine had is gone or reordered: a later stage only inserts or appends.
      for (const key of ['stages', 'processes', 'tables', 'capabilities', 'guiPanels', 'portRoles'] as const) {
        expect(now[key].filter((x) => p2[key].includes(x)), key).toEqual(p2[key]);
      }
      const later = now.stages.filter((s) => !p2.stages.includes(s));
      // Every daemon outside the P2 list is of a later stage: each of its CAPABILITY_PROCESSES rows has a later `since`.
      const rows = Object.values(CAPABILITY_PROCESSES).flat();
      for (const name of now.processes.filter((x) => !p2.processes.includes(x))) {
        const since = rows.filter((r) => r.process === name).map((r) => String(r.since));
        expect(since.filter((s) => !later.includes(s)), name).toEqual([]);
      }
      // Every table outside the P2 list has a later-stage descriptor.
      const descriptors = TABLE_DESCRIPTORS as unknown as Readonly<Record<string, { readonly since: string }>>;
      for (const name of now.tables.filter((x) => !p2.tables.includes(x))) expect(later, name).toContain(descriptors[name]?.since);
      // The per-device rule itself, on a synthetic P3-shaped snapshot (D22: a managed switch loses the later-stage
      // udp/tcp and their sockets table; a router keeps its P1 udp/tcp; later-stage tables and members go).
      const c = normalisationCase();
      expect(normaliseSnapshot(c.input, c.vocab, c.contracts)).toEqual(c.expected);
    });

    for (const w of shardWorlds(shard)) {
      it(`${w.name}: every event digest, window and stored line, the typed results and the normalised snapshot equal the P2 golden`, () => {
        const expected = golden().worlds[w.name];
        if (expected === undefined) return assert.fail(`${w.name} has no entry in test/goldens/p2-profile-digests.json`);
        const run = freshRun(w);
        expect(run.refused, `${w.name}: setup lines the CLI refused`).toEqual([]);
        expect(run.dropped, `${w.name}: trace events evicted before they were digested`).toBe(0);

        const events = eventReport(w.name, expected, run);
        if (events !== '') assert.fail(events);
        expect(run.entry.typed, `${w.name}: the typed results`).toEqual(expected.typed);
        const snapshot = snapshotReport(w.name, expected, run);
        if (snapshot !== '') assert.fail(snapshot);
        expect(run.entry).toEqual(expected);
      }, SHARD_CASE_TIMEOUT_MS);
    }
  });
}
